def t(language: str, key: str) -> str:
    """Gabarit brut (non formaté) pour `key`, dans `language` (repli sur le français)."""
    table = STRINGS.get(language) or STRINGS["fr"]
    return table.get(key, STRINGS["fr"][key])


def n(language: str, count: int, one: str, many: str) -> str:
    """Nombre + forme fr/en accordée, à partir de deux clés de la table."""
    word = t(language, one if count == 1 else many)
    return f"{count} {word}"
