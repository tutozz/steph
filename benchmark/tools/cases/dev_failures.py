"""Synthetic build failures, runtime errors and test-runner outputs.

Compilers, tracebacks, pytest, cargo and jest outputs stay English in both languages;
only the coreutils/shell messages that a real locale would translate (permission denied,
command not found) carry a distinct French output. Long build outputs use a fixed-seed
random generator for the surrounding noise, kept deterministic across runs.

SPDX-License-Identifier: MIT
"""

import random


def synth(**case) -> dict:
    return {"origin": "synthetic", "split": "test", "task": "summary", "forbidden": [], **case}


def _cargo_noise(seed: int, n: int) -> list:
    crates = [
        "libc", "serde", "syn", "quote", "proc-macro2", "cfg-if", "memchr", "autocfg",
        "num-traits", "itoa", "ryu", "unicode-ident", "version-check", "once-cell",
        "smallvec", "bitflags", "getrandom", "rand-core", "ppv-lite86", "zeroize",
        "subtle", "typenum", "generic-array", "block-buffer", "crypto-common",
        "cpufeatures", "rustversion", "heck", "unicode-xid", "lock-api",
    ]
    rng = random.Random(seed)
    return [f"   Compiling {rng.choice(crates)} v{rng.randint(0, 2)}.{rng.randint(0, 60)}.{rng.randint(0, 20)}"
            for _ in range(n)]


def _maven_noise(seed: int, n: int) -> list:
    artifacts = [
        "commons-lang3", "commons-io", "guava", "jackson-databind", "jackson-core",
        "slf4j-api", "logback-classic", "junit-jupiter", "mockito-core", "spring-core",
        "spring-context", "hibernate-core", "httpclient", "gson", "commons-collections4",
        "checker-qual", "error-prone-annotations", "failureaccess", "animal-sniffer-annotations",
    ]
    rng = random.Random(seed)
    lines = []
    for _ in range(n):
        art = rng.choice(artifacts)
        ver = f"{rng.randint(1, 5)}.{rng.randint(0, 20)}.{rng.randint(0, 9)}"
        lines.append(f"[INFO] Downloading from central: "
                     f"https://repo.maven.apache.org/maven2/org/example/{art}/{ver}/{art}-{ver}.jar")
    return lines


