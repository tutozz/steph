"""Synthetic git and package-manager outputs for Steph Speak Bench.

Git porcelain messages (Auto-merging, CONFLICT, hints, fatal:, Fast-forward, the
diffstat summary line) are localized under a French locale, so those cases carry
{"en": ..., "fr": ...} outputs. Compilers and package managers with no i18n of their
own (npm, pip, Homebrew) stay English in both, only the spoken reference changes
language. Long outputs use a fixed-seed random.Random so the module stays
deterministic across runs.

SPDX-License-Identifier: MIT
"""

import random

GIT_LOCALE_NOTE = "Git porcelain messages localized under a French locale; the English output is the C locale run."


def synth(**case) -> dict:
    return {"origin": "synthetic", "split": "test", "task": "summary", "forbidden": [], **case}


def _npm_deprecated_lines(seed: int, n: int) -> list:
    packages = [
        ("core-js", "2.6.12", "core-js@<3.23.3 is no longer maintained"),
        ("request", "2.88.2", "request has been deprecated, see https://github.com/request/request/issues/3142"),
        ("uuid", "3.4.0", "please upgrade to version 7 or higher"),
        ("querystring", "0.2.1", "the querystring API is considered legacy"),
        ("har-validator", "5.1.5", "this library is no longer supported"),
        ("stable", "0.1.8", "modern JS already guarantees Array#sort() is a stable sort"),
        ("inflight", "1.0.6", "this module is not supported, leaks memory"),
        ("rimraf", "2.7.1", "please upgrade to rimraf 4"),
        ("glob", "7.2.3", "glob versions prior to v9 are no longer supported"),
        ("babel-eslint", "10.1.0", "babel-eslint is now @babel/eslint-parser"),
    ]
    rng = random.Random(seed)
    return [f"npm warn deprecated {name}@{ver}: {msg}" for name, ver, msg in
            (rng.choice(packages) for _ in range(n))]


